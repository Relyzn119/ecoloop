<?php

namespace App\Services;

use App\Models\AgentLog;
use App\Models\DonationPartner;
use App\Models\Product;
use Illuminate\Database\Eloquent\Collection;
use Illuminate\Support\Facades\DB;
use InvalidArgumentException;

class InventoryService
{
    /**
     * Retrieve active products expiring within the specified days threshold.
     *
     * @param  int  $daysThreshold  Number of days from today to consider as expiring soon
     * @return Collection<int, Product>
     */
    public function getExpiringProducts(int $daysThreshold = 7): Collection
    {
        $today = now()->toDateString();
        $targetDate = now()->addDays($daysThreshold)->toDateString();

        return Product::query()
            ->with(['category:id,name,slug'])
            ->whereIn('status', ['active', 'discounted'])
            ->whereDate('expiration_date', '>=', $today)
            ->whereDate('expiration_date', '<=', $targetDate)
            ->orderBy('expiration_date', 'asc')
            ->orderBy('quantity', 'desc')
            ->get();
    }

    /**
     * Apply a markdown discount to a product and write an audit entry into agent_logs.
     *
     * @param  int  $productId  Target product ID
     * @param  float  $discountPercentage  Percentage discount (e.g. 20, 50)
     * @param  string  $reason  Rationale generated by AI or operator
     * @return Product Updated product instance
     *
     * @throws InvalidArgumentException
     */
    public function applyDiscount(int $productId, float $discountPercentage, string $reason): Product
    {
        if ($discountPercentage <= 0 || $discountPercentage >= 100) {
            throw new InvalidArgumentException('Discount percentage must be greater than 0 and less than 100.');
        }

        return DB::transaction(function () use ($productId, $discountPercentage, $reason) {
            /** @var Product $product */
            $product = Product::query()->lockForUpdate()->findOrFail($productId);

            $originalPrice = (float) $product->original_price;
            $discountPrice = round($originalPrice * (1 - ($discountPercentage / 100)), 2);

            $product->update([
                'status' => 'discounted',
                'discount_price' => $discountPrice,
            ]);

            AgentLog::create([
                'product_id' => $product->id,
                'action_type' => 'discount_applied',
                'reasoning' => $reason,
                'payload' => [
                    'product_sku' => $product->sku,
                    'original_price' => $originalPrice,
                    'discount_percentage' => $discountPercentage,
                    'new_discount_price' => $discountPrice,
                    'applied_at' => now()->toIso8601String(),
                ],
                'status' => 'success',
            ]);

            return $product->fresh(['category', 'agentLogs']);
        });
    }

    /**
     * Reserve a product for donation to a partner and log the audit entry.
     *
     * @param  int  $productId  Target product ID
     * @param  int  $partnerId  Target donation partner ID
     * @param  string  $reason  Rationale for donation
     * @return Product Updated product instance
     */
    public function reserveForDonation(int $productId, int $partnerId, string $reason): Product
    {
        return DB::transaction(function () use ($productId, $partnerId, $reason) {
            /** @var Product $product */
            $product = Product::query()->lockForUpdate()->findOrFail($productId);

            /** @var DonationPartner $partner */
            $partner = DonationPartner::query()->findOrFail($partnerId);

            $product->update([
                'status' => 'reserved_donation',
            ]);

            AgentLog::create([
                'product_id' => $product->id,
                'action_type' => 'donation_requested',
                'reasoning' => $reason,
                'payload' => [
                    'product_sku' => $product->sku,
                    'product_name' => $product->name,
                    'quantity' => $product->quantity,
                    'unit' => $product->unit,
                    'partner_id' => $partner->id,
                    'partner_name' => $partner->name,
                    'partner_email' => $partner->email,
                    'reserved_at' => now()->toIso8601String(),
                ],
                'status' => 'success',
            ]);

            return $product->fresh(['category', 'agentLogs']);
        });
    }

    /**
     * Autonomous Mock AI simulation runner for local testing and demonstration.
     * Evaluates expiring items and applies intelligent markdowns or donation reserves.
     *
     * @param  int  $daysThreshold  Threshold in days to analyze
     * @return array<string, mixed>
     */
    public function simulateAiEvaluation(int $daysThreshold = 3): array
    {
        $expiring = $this->getExpiringProducts($daysThreshold);
        $partner = DonationPartner::query()->where('is_active', true)->first();

        $actionsTaken = [];

        foreach ($expiring as $product) {
            $daysLeft = (int) now()->startOfDay()->diffInDays($product->expiration_date, false);

            if ($daysLeft <= 1 && $partner && $product->status !== 'reserved_donation') {
                // Reserve for donation if less than 24-48 hours remaining
                $reason = sprintf(
                    'Autonomous AI Decision: %s has only %d day(s) shelf life remaining. Reserved for immediate cold-chain pickup by %s to eliminate organic landfill waste.',
                    $product->name,
                    max(0, $daysLeft),
                    $partner->name
                );

                $updated = $this->reserveForDonation($product->id, $partner->id, $reason);

                $actionsTaken[] = [
                    'action' => 'reserve_donation',
                    'product_id' => $updated->id,
                    'sku' => $updated->sku,
                    'name' => $updated->name,
                    'partner' => $partner->name,
                    'reason' => $reason,
                ];
            } elseif ($daysLeft <= 3 && $product->status === 'active') {
                // Apply dynamic 40% discount for items within 3 days
                $discountPct = $daysLeft <= 2 ? 50.0 : 30.0;
                $reason = sprintf(
                    'Autonomous AI Decision: %s shelf-life is %d days. Applied %.0f%% dynamic promotional markdown to maximize customer clearance velocity.',
                    $product->name,
                    $daysLeft,
                    $discountPct
                );

                $updated = $this->applyDiscount($product->id, $discountPct, $reason);

                $actionsTaken[] = [
                    'action' => 'apply_discount',
                    'product_id' => $updated->id,
                    'sku' => $updated->sku,
                    'name' => $updated->name,
                    'discount_percentage' => $discountPct,
                    'discount_price' => $updated->discount_price,
                    'reason' => $reason,
                ];
            }
        }

        return [
            'analyzed_count' => $expiring->count(),
            'actions_count' => count($actionsTaken),
            'actions' => $actionsTaken,
            'simulated_at' => now()->toIso8601String(),
        ];
    }
}
