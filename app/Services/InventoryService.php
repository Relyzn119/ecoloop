    /**
     * Retrieve active products expiring within the specified days threshold.
     *
     * @param  int  $daysThreshold  Number of days from today to consider as expiring soon
     * @return Collection<int, Product>
     */
    public function getExpiringProducts(int $daysThreshold = 7): Collection
    {
        $today = now()->toDateString();
        $targetDate = now()->addDays($daysThreshold)->toDateString();

        return Product::query()
            ->with(['category:id,name,slug'])
            ->whereIn('status', ['active', 'discounted'])
            ->whereDate('expiration_date', '>=', $today)
            ->whereDate('expiration_date', '<=', $targetDate)
            ->orderBy('expiration_date', 'asc')
            ->orderBy('quantity', 'desc')
            ->get();
    }

    /**
     * Apply a markdown discount to a product and write an audit entry into agent_logs.
     *
     * @param  int  $productId  Target product ID
     * @param  float  $discountPercentage  Percentage discount (e.g. 20, 50)
     * @param  string  $reason  Rationale generated by AI or operator
     * @return Product Updated product instance
     *
     * @throws InvalidArgumentException
     */
    public function applyDiscount(int $productId, float $discountPercentage, string $reason): Product
    {
        if ($discountPercentage <= 0 || $discountPercentage >= 100) {
            throw new InvalidArgumentException('Discount percentage must be greater than 0 and less than 100.');
        }

        $product = DB::transaction(function () use ($productId, $discountPercentage, $reason) {
            /** @var Product $product */
            $product = Product::query()->lockForUpdate()->findOrFail($productId);

            $originalPrice = (float) $product->original_price;
            $discountPrice = round($originalPrice * (1 - ($discountPercentage / 100)), 2);

            $product->update([
                'status' => 'discounted',
                'discount_price' => $discountPrice,
            ]);
            $this->ensureLegacyBatch($product);
            $product->batches()->where('quantity_available', '>', 0)->update([
                'status' => 'discounted',
                'discount_price' => $discountPrice,
            ]);

            AgentLog::create([
                'product_id' => $product->id,
                'action_type' => 'discount_applied',
                'reasoning' => $reason,
                'payload' => [
                    'product_sku' => $product->sku,
                    'original_price' => $originalPrice,
                    'discount_percentage' => $discountPercentage,
                    'new_discount_price' => $discountPrice,
                    'applied_at' => now()->toIso8601String(),
                ],
                'status' => 'success',
            ]);

            return $product->fresh(['category', 'agentLogs']);
        });

        foreach ($product->batches()->where('status', 'discounted')->where('quantity_available', '>', 0)->get() as $batch) {
            $this->notificationService->queueDiscountOffer(
                $product,
                $batch,
                (int) round($discountPercentage),
                'batch:'.$batch->id.':'.$batch->updated_at?->timestamp
            );
        }

        return $product;
    }

    /** Create pending approvals without changing any batch or product price. */
    public function requestDiscountApproval(int $productId, int $discountPercentage, string $reason): array
    {
        if ($discountPercentage < 1 || $discountPercentage > 50) {
            throw new InvalidArgumentException('Discount recommendations must be between 1% and 50%.');
        }

        $product = Product::query()->findOrFail($productId);
        $this->ensureLegacyBatch($product);
        $approvals = [];

        foreach ($product->batches()->where('quantity_available', '>', 0)->get() as $batch) {
            $approval = DiscountApproval::query()->firstOrCreate(
                ['product_batch_id' => $batch->id, 'status' => 'pending'],
                [
                    'product_id' => $product->id,
                    'recommended_percentage' => $discountPercentage,
                    'recommended_price' => round((float) $batch->original_price * (1 - ($discountPercentage / 100)), 2),
                    'reasoning' => $reason,
                ]
            );
            if ($approval->wasRecentlyCreated) {
                $this->notificationService->queueDiscountApproval($approval);
            }
            $approvals[] = $approval;
        }

        return $approvals;
    }

    /** Preview available product quantity in batches expiring within seven days. */
    public function previewExpiringDonation(int $productId): array
