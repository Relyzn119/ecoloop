            if ($batch->source !== 'central_sync'
                || $batch->quantity_available < 1
                || ! in_array($batch->status, ['active', 'discounted'], true)
                || $batch->expiration_date->lt(now()->startOfDay())
                || $batch->expiration_date->gt(now()->addDays(2)->endOfDay())) {
                return null;
            }

            $stockBefore = (int) $product->batches()->sum('quantity_available');
            $quantity = $batch->quantity_available;
            $batch->update([
                'quantity_available' => 0,
                'quantity_donated' => $batch->quantity_donated + $quantity,
                'status' => 'donated',
            ]);

            AgentLog::query()->create([
                'product_id' => $product->id,
                'partner_id' => $partner->id,
                'action_type' => 'donation_requested',
                'reasoning' => $reason,
                'payload' => [
                    'event_type' => 'donation_completed',
                    'source' => 'demo_sync_now',
                    'batch_id' => $batch->id,
                    'batch_code' => $batch->batch_code,
                    'quantity_donated' => $quantity,
                    'unit' => $product->unit,
                    'partner_id' => $partner->id,
                ],
                'status' => 'success',
            ]);

            $this->refreshProductStockSummary($product->id);

            return [
                'partner' => $partner,
                'product' => $product->fresh(),
                'batch' => $batch->fresh(),
                'quantity' => $quantity,
                'reason' => $reason,
                'stock_before' => $stockBefore,
                'stock_after' => $stockBefore - $quantity,
            ];
        });

        if ($donation === null) {
            return ['success' => false, 'quantity' => 0, 'batch_id' => $batchId];
        }

        app(N8nFinalEventService::class)->queue(
            'donation.completed',
            'donation-batch:'.$donation['batch']->id.':'.$donation['batch']->updated_at?->timestamp,
            [
                'product_id' => $donation['product']->id,
                'product_name' => $donation['product']->name,
                'batch_id' => $donation['batch']->id,
                'partner_id' => $donation['partner']->id,
                'quantity' => $donation['quantity'],
                'unit' => $donation['product']->unit,
            ]
        );

        $notificationsQueued = true;
        try {
            $this->notificationService->queueDonationAlerts(
                $donation['partner'],
                $donation['product'],
                $donation['batch'],
                $donation['reason'],
                broadcastToActivePartners: true
            );
        } catch (Throwable $exception) {
            $notificationsQueued = false;
            Log::error('Demo donation succeeded but notification queueing failed.', [
                'batch_id' => $donation['batch']->id,
                'partner_id' => $donation['partner']->id,
                'error' => $exception->getMessage(),
            ]);
        }

        return [
            'success' => true,
            'product_id' => $donation['product']->id,
            'quantity' => $donation['quantity'],
            'unit' => $donation['product']->unit,
            'product_name' => $donation['product']->name,
            'sku' => $donation['product']->sku,
            'batch_id' => $donation['batch']->id,
            'batch_code' => $donation['batch']->batch_code,
            'expiration_date' => $donation['batch']->expiration_date->toDateString(),
            'stock_before' => $donation['stock_before'],
            'stock_after' => $donation['stock_after'],
            'partner_name' => $donation['partner']->name,
            'notifications_queued' => $notificationsQueued,
        ];
    }

    /**
     * Evaluate expiring inventory with the configured AI provider and execute
     * the resulting inventory actions.
     *
     * @param  int  $daysThreshold  Threshold in days to analyze
     * @return array<string, mixed>
     */
    public function simulateAiEvaluation(int $daysThreshold = 7): array
    {
        $expiring = $this->getExpiringProducts($daysThreshold);
        $actionsTaken = [];
        $skipped = [];

        foreach ($expiring as $product) {
            $result = $this->evaluateProductBatches($product, $daysThreshold);

            foreach ($result['results'] as $batchResult) {
                if ($batchResult['action'] === 'skipped') {
                    $skipped[] = [
                        'product_id' => $product->id,
                        'batch_id' => $batchResult['batch_id'],
                        'reason' => $batchResult['reason'],
                    ];

                    continue;
                }

                if (in_array($batchResult['action'], ['donated', 'awaiting_discount_approval'], true)) {
                    $actionsTaken[] = [
                        'action' => $batchResult['action'],
                        'product_id' => $product->id,
                        'sku' => $product->sku,
                        'name' => $product->name,
                        ...$batchResult,
                    ];
                }
            }
        }

        return [
            'analyzed_count' => $expiring->count(),
            'actions_count' => count($actionsTaken),
            'actions' => $actionsTaken,
            'skipped_count' => count($skipped),
            'skipped' => $skipped,
            'simulated_at' => now()->toIso8601String(),
        ];
    }

    /**
     * Evaluate all eligible batches for one product after inventory intake.
     * Donation and approval records are scoped to the expiring batch only.
     *
     * @return array<string, mixed>
     */
    public function evaluateProductBatches(Product $product, int $daysThreshold = 7): array
    {
        $this->ensureLegacyBatch($product);
        $aiAgentService = app(AiAgentService::class);
        $processed = [];

        $batches = $product->batches()
            ->where('quantity_available', '>', 0)
            ->whereIn('status', ['active', 'discounted'])
            ->whereDate('expiration_date', '>=', now()->toDateString())
            ->whereDate('expiration_date', '<=', now()->addDays($daysThreshold)->toDateString())
            ->orderBy('expiration_date')
            ->get();

        foreach ($batches as $batch) {
            $evaluationProduct = $product->replicate();
            $evaluationProduct->id = $product->id;
            $evaluationProduct->setRelation('category', $product->category);
            $evaluationProduct->quantity = $batch->quantity_available;
            $evaluationProduct->expiration_date = $batch->expiration_date;
            $evaluationProduct->original_price = $batch->original_price;
            $evaluationProduct->discount_price = $batch->discount_price;

            $decision = $aiAgentService->evaluateProduct($evaluationProduct, '9router');
            $daysRemaining = now('Asia/Jakarta')->startOfDay()->diffInDays($batch->expiration_date->startOfDay(), false);
            $hasLiveAiDecision = ($decision['provider'] ?? null) === '9router';
            $discountWindow = $daysRemaining > 3 && $daysRemaining < 7;

            if (! $hasLiveAiDecision && ! $discountWindow && $daysRemaining > 3) {
                $processed[] = [
                    'batch_id' => $batch->id,
                    'action' => 'skipped',
                    'reason' => '9Router did not return a live model decision; no inventory change was applied.',
                ];

                continue;
            }

            $reason = $hasLiveAiDecision
                ? (string) ($decision['reasoning'] ?? 'AI evaluated the inventory batch.')
                : ($daysRemaining <= 2
                    ? 'Fallback expiry policy recommends manager review for donation because this batch expires in '.$daysRemaining.' day(s). No donation is executed before approval.'
                    : '9Router did not return a live decision. EcoLoop created a 30% discount recommendation because this batch expires in '.$daysRemaining.' days; manager or cashier approval is required and the price is unchanged.');

            if ($daysRemaining === 3) {
                $approvalCount = app(ExpiringDonationApprovalService::class)->createApprovalForBatch($batch, true);
                $processed[] = [
                    'batch_id' => $batch->id,
                    'action' => $approvalCount > 0 ? 'donation_prealert_sent' : 'donation_prealert_unavailable',
                    'eligible_on' => $batch->expiration_date->toDateString(),
                    'quantity' => $batch->quantity_available,
                ];

                continue;
            }

            if ($daysRemaining <= 2) {
                $approvalCount = app(ExpiringDonationApprovalService::class)->createApprovalForBatch($batch, false, $reason, $decision);
                $processed[] = [
                    'batch_id' => $batch->id,
                    'action' => $approvalCount > 0 ? 'awaiting_donation_approval' : 'donation_approval_unavailable',
                    'quantity' => (int) ($decision['recommended_donation_quantity'] ?? $batch->quantity_available),
                ];

                continue;
            }

            if ($discountWindow) {
                $aiRecommendedDiscount = $hasLiveAiDecision && ($decision['action'] ?? null) === 'discount';
                $percentage = $aiRecommendedDiscount
                    ? max(1, min(50, (int) round((float) ($decision['discount_percentage'] ?? 30))))
                    : 30;
                if (! $aiRecommendedDiscount && $hasLiveAiDecision) {
                    $reason = 'EcoLoop policy created a 30% discount recommendation because this batch expires in '.$daysRemaining.' days. AI reasoning: '.$reason;
                }
                $price = round((float) $batch->original_price * (1 - ($percentage / 100)), 2);

                $approval = DiscountApproval::query()->firstOrCreate(
                    [
                        'product_batch_id' => $batch->id,
                        'status' => 'pending',
                    ],
                    [
                        'product_id' => $product->id,
                        'recommended_percentage' => $percentage,
                        'recommended_price' => $price,
                        'reasoning' => $reason,
                    ]
                );
                if ($approval->wasRecentlyCreated) {
                    $this->notificationService->queueDiscountApproval($approval);
                }

                $processed[] = [
                    'batch_id' => $batch->id,
                    'action' => 'awaiting_discount_approval',
                    'approval_id' => $approval->id,
                    'recommended_percentage' => $percentage,
                    'recommended_price' => $price,
                ];

                continue;
            }

            $processed[] = ['batch_id' => $batch->id, 'action' => 'none'];
        }

        return [
            'product_id' => $product->id,
            'batch_count' => $batches->count(),
            'results' => $processed,
            'product' => $product->fresh(),
        ];
    }

    private function ensureLegacyBatch(Product $product): void
    {
        if ($product->batches()->exists()) {
            return;
        }

        ProductBatch::query()->create([
            'product_id' => $product->id,
            'batch_code' => 'LEGACY-'.$product->id,
            'quantity_received' => max(0, (int) $product->quantity),
            'quantity_available' => max(0, (int) $product->quantity),
            'expiration_date' => $product->expiration_date,
            'original_price' => $product->original_price,
            'discount_price' => $product->discount_price,
            'status' => $product->status,
            'source' => 'legacy',
            'source_reference' => (string) $product->id,
        ]);
    }

    public function refreshProductStockSummary(int $productId): void
    {
        $product = Product::query()->lockForUpdate()->findOrFail($productId);
        $availableBatches = $product->batches()->where('quantity_available', '>', 0)->get();
        $quantity = (int) $availableBatches->sum('quantity_available');
        $earliestExpiration = $availableBatches->min('expiration_date');
        $hasFullPriceStock = $availableBatches->contains(fn (ProductBatch $batch): bool => $batch->status !== 'discounted');
        $quantitySold = (int) $product->batches()->sum('quantity_sold');
        $quantityDonated = (int) $product->batches()->sum('quantity_donated');
        $status = match (true) {
            $quantity > 0 => $hasFullPriceStock ? 'active' : 'discounted',
            $quantitySold > 0 => 'sold_out',
            $quantityDonated > 0 => 'donated',
            default => 'disposed',
        };

        $product->update([
            'quantity' => $quantity,
            'expiration_date' => $earliestExpiration ?? $product->expiration_date,
            'status' => $status,
        ]);
    }
